// ── Category helpers ────────────────────────────────────────────────────────

const CATEGORIES = ['Produce', 'Meat & Seafood', 'Dairy', 'Pantry', 'Frozen', 'Other'];

function categorize(name: string): string {
  const n = name.toLowerCase();
  if (/tomato|cucumber|onion|garlic|ginger|lemon|lime|lettuce|spinach|kale|pepper|capsicum|carrot|zucchini|mushroom|broccoli|cauliflower|celery|herb|basil|parsley|coriander|cilantro|thyme|rosemary|mint|avocado|sweet potato|potato|corn|pea|bean sprout|bok choy/.test(n)) return 'Produce';
  if (/chicken|beef|pork|lamb|turkey|duck|salmon|tuna|shrimp|prawn|fish|cod|tilapia|crab|lobster|bacon|pancetta|sausage|mince|steak|fillet/.test(n)) return 'Meat & Seafood';
  if (/milk|cheese|cream|butter|yogurt|feta|parmesan|mozzarella|cheddar|brie|gouda|egg|creme fraiche|mascarpone/.test(n)) return 'Dairy';
  if (/pasta|spaghetti|rice|flour|oil|olive oil|salt|pepper|spice|cumin|masala|paprika|turmeric|oregano|cinnamon|sauce|bread|tortilla|soy sauce|fish sauce|vinegar|sugar|honey|stock|broth|lentil|chickpea|coconut milk|tomato paste|canned|tinned/.test(n)) return 'Pantry';
  if (/frozen|ice cream/.test(n)) return 'Frozen';
  return 'Other';
}

function buildClipboardText(items: GroceryItem[], recipes: Recipe[], date: string): string {
  const grouped: Record<string, GroceryItem[]> = {};
  for (const item of items) {
    if (item.checked) continue;
    const cat = categorize(item.ingredient_name);
    if (!grouped[cat]) grouped[cat] = [];
    grouped[cat].push(item);
  }

  const lines: string[] = [
    `Mori Grocery List — ${date}`,
    recipes.length > 0 ? `Meals: ${recipes.map((r) => r.title).join(', ')}` : '',
    '',
  ].filter((l, i) => i !== 1 || l !== '');

  for (const cat of CATEGORIES) {
    if (!grouped[cat]?.length) continue;
    lines.push(cat.toUpperCase());
    for (const item of grouped[cat]) {
      const qty = item.quantity ? ` — ${item.quantity}${item.unit ? ' ' + item.unit : ''}` : '';
      lines.push(`• ${item.ingredient_name}${qty}`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('Generated by Mori');
  return lines.join('\n');
}

