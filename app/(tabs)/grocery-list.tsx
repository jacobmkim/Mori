  const [instacartError, setInstacartError] = useState<string | null>(null);
  const [pantryNames, setPantryNames] = useState<Set<string>>(() => new Set());
  const [skippedModalVisible, setSkippedModalVisible] = useState(false);
  // forcedStaples: raw ingredient_name keys; resets per session (not persisted).
  const [forcedStaples, setForcedStaples] = useState<Set<string>>(() => new Set());
  // skippedPantry: normalized keys (see normKey); resets per session.
  const [skippedPantry, setSkippedPantry] = useState<Set<string>>(() => new Set());
  // Confirm dialog shown right before sending to Instacart when items are being left out.
  const [confirmSend, setConfirmSend] = useState<{ sendable: GroceryItem[]; skipped: GroceryItem[] } | null>(null);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      const { data: { session } } = await supabase.auth.getSession();
      const uid = session?.user?.id;
      if (!uid) return;
      try {
        const rows = await getPantryItems(uid);
        if (cancelled) return;
        setPantryNames(new Set(
          rows
            .map((r) => r.ingredient_name?.trim().toLowerCase())
            .filter((n): n is string => !!n)
        ));
      } catch {
        // Non-blocking: pantry filter just becomes a no-op if fetch fails.
      }
    })();
    return () => { cancelled = true; };
  }, []);

  // Fetch and aggregate macros for all selected recipes whenever the meal selection changes.
  // TheMealDB recipes have empty ingredients[] — fetch detail first to get real ingredient data.
  useEffect(() => {
    if (selectedRecipes.length === 0) { setCombinedMacros(null); return; }
    let cancelled = false;

    async function fetchAll() {
      const results = await Promise.all(
        selectedRecipes.map(async (r) => {
          // Get ingredient data — prefer existing, fall back to MealDetail fetch
          let ings = r.ingredients;
          if (ings.length === 0) {
            const detail = await fetchMealDetail(r.id).catch(() => null);
            ings = (detail?.ingredients ?? []).map((i) => ({ name: i.name, quantity: i.measure, unit: '' }));
          }
          return fetchMacros(r.title, ings, { externalId: r.id }).catch(() => null);
        })
      );
      if (cancelled) return;
      const valid = results.filter(Boolean) as Macros[];
      if (valid.length === 0) { setCombinedMacros(null); return; }
      setCombinedMacros({
        calories: valid.reduce((s, m) => s + m.calories, 0),
        protein: valid.reduce((s, m) => s + m.protein, 0),
        carbohydrates: valid.reduce((s, m) => s + m.carbohydrates, 0),
        fat: valid.reduce((s, m) => s + m.fat, 0),
        fibre: valid.reduce((s, m) => s + m.fibre, 0),
        isEstimated: valid.some((m) => m.isEstimated),
      });
    }

    fetchAll();
    return () => { cancelled = true; };
  }, [selectedRecipes.map((r) => r.id).join(',')]);

  function triggerUndo(items: GroceryItem[]) {
    setUndoItems(items);
    setUndoKey((k) => k + 1);
  }

  const items = list?.items ?? [];
  const checkedCount = items.filter((i) => i.checked).length;
  const uncheckedCount = items.length - checkedCount;

  const { pantryHints, skippedItems } = useMemo(
    () => partitionForInstacart(items.filter((i) => !i.checked), pantryNames),
    [items, pantryNames],
  );

  // Notice line counts only staples the user hasn't pulled back via the modal.
  const displayedSkippedStaples = skippedItems.filter(
    (i) => !forcedStaples.has(i.ingredient_name),
  ).length;

  // Build a quick lookup: recipeId → title
  const recipeMap = Object.fromEntries(selectedRecipes.map((r) => [r.id, r.title]));

  // Group unchecked items by category
  const grouped: Record<string, GroceryItem[]> = {};
  for (const item of items) {
    if (item.checked) continue;
    const cat = categorize(item.ingredient_name);
    if (!grouped[cat]) grouped[cat] = [];
    grouped[cat].push(item);
  }
  const checkedItems = items.filter((i) => i.checked);
  const categoriesWithItems = CATEGORIES.filter((c) => grouped[c]?.length > 0);

  function handleClearChecked() {
    const removed = clearChecked();
    if (removed.length > 0) triggerUndo(removed);
  }

  function handleUndo() {
    if (!undoItems) return;
    restoreItems(undoItems);
    setUndoItems(null);
  }

  async function handleCopy() {
    const date = new Date().toLocaleDateString('en-US', {
      month: 'long', day: 'numeric', year: 'numeric',
    });
    const text = buildClipboardText(items, selectedRecipes, date);
    await Clipboard.setStringAsync(text);
    Alert.alert('Copied!', 'Your grocery list has been copied to the clipboard.');
  }

  function cleanForSearch(name: string): string {
    // Only strip words that are pure prep (verbs the cook does) or non-product-defining
    // descriptors. Words like canned/frozen/dried/ground/crushed/whole identify a
    // DIFFERENT product on Instacart (canned crushed tomatoes ≠ fresh tomatoes;
    // ground beef ≠ steak; dried oregano ≠ fresh oregano) — never strip them.
    return name
      .replace(/\(.*?\)/g, '')
      // strip leading quantity + optional unit (e.g. "2 cups", "1/2 lb", "500g", "3")
      .replace(/^\d[\d\s/]*\s*(tsp|tbsp|teaspoon|tablespoon|cup|cups|oz|lb|lbs|g|kg|ml|l|clove|cloves|bunch|bunches|head|heads|piece|pieces|can|cans|stalk|stalks|sprig|sprigs|slice|slices)?\s*/i, '')
      // strip prep words after a comma ("onion, diced" → "onion")
      .replace(/,\s*(diced|minced|chopped|sliced|grated|julienned|peeled|deveined|trimmed|cubed|shredded|melted|softened|beaten|divided|optional|to taste|for garnish|for serving|as needed).*/i, '')
      // strip prep words not after a comma ("diced onion" → "onion")
      .replace(/\b(diced|minced|chopped|sliced|grated|julienned|peeled|deveined|trimmed|cubed|shredded|melted|softened|beaten|divided)\b/gi, '')
      // strip non-product descriptors (size, prep adverbs, preference flags)
      .replace(/\b(large|medium|small|extra-virgin|organic|finely|roughly|thinly)\b/gi, '')
      .replace(/\s{2,}/g, ' ')
      .trim();
  }

  function getUncheckedItemNames() {
    return items.filter((i) => !i.checked).map((i) => cleanForSearch(i.ingredient_name));
  }

  async function submitToInstacart(itemsToSend: GroceryItem[]) {
    setInstacartLoading(true);
    setInstacartError(null);

    try {
      const { data: { session } } = await supabase.auth.getSession();

      const instacartItems = itemsToSend.map((i) => {
        const name = cleanForSearch(i.ingredient_name);
        const rawMeasurement = parseGroceryMeasurement(i.quantity, i.unit);
        const measurement = rawMeasurement && unitSystem === 'us'
          ? convertMeasurementToUs(rawMeasurement)
          : rawMeasurement;
        const displayText = i.quantity
          ? `${i.ingredient_name} ${i.quantity}${i.unit ? ' ' + i.unit : ''}`.trim()
          : i.ingredient_name;
        return { name, displayText, ...(measurement ? { measurement } : {}) };
      });

      const title = selectedRecipes.length > 0
        ? `Mori: ${selectedRecipes.slice(0, 2).map((r) => r.title).join(', ')}${selectedRecipes.length > 2 ? ` +${selectedRecipes.length - 2} more` : ''}`
        : 'Mori Grocery List';

      const res = await fetch(`${getApiBaseUrl()}/api/instacart-cart`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(session?.access_token ? { Authorization: `Bearer ${session.access_token}` } : {}),
        },
        body: JSON.stringify({ items: instacartItems, title }),
      });

      if (!res.ok) throw new Error(`instacart-cart ${res.status}`);
      const data = await res.json();
      await WebBrowser.openBrowserAsync(data.url);
    } catch {
      setInstacartError('Could not create Instacart list. Please try again.');
    } finally {
      setInstacartLoading(false);
    }
  }

  async function handleInstacartOrder() {
    const uncheckedItems = items.filter((i) => !i.checked);
    if (uncheckedItems.length === 0) {
      Alert.alert('No items', 'All items are already checked off.');
      return;
    }

    const { sendable: baseSendable, skippedItems: allStaples } = partitionForInstacart(uncheckedItems, pantryNames);
    const finalSendable = [
      ...baseSendable.filter((i) => !skippedPantry.has(normKey(i))),
      ...allStaples.filter((i) => forcedStaples.has(i.ingredient_name)),
    ];

    if (finalSendable.length === 0) {
      const droppedNames = uncheckedItems.map((i) => i.ingredient_name);
      const previewNames = droppedNames.slice(0, 3).join(', ');
      const more = droppedNames.length > 3 ? ` …and ${droppedNames.length - 3} more` : '';
      const hasStaples = allStaples.length > 0;
      const buttons: { text: string; style?: 'cancel' | 'default'; onPress?: () => void }[] = [
        { text: 'Cancel', style: 'cancel' },
      ];
      if (hasStaples) {
        buttons.push({ text: 'Review', onPress: () => setSkippedModalVisible(true) });
      }
      buttons.push({ text: 'Send anyway', onPress: () => submitToInstacart(uncheckedItems) });
      Alert.alert(
        'Cart would be empty',
        `These items would be skipped: ${previewNames}${more}. Send them anyway?`,
        buttons,
      );
      return;
    }

    // Surface what's being left out so the user can catch surprises (e.g. fresh
    // garlic that only lives in STAPLES, or a pantry hint they actively skipped)
    // before the browser opens.
    const skippedFromCart = [
      ...allStaples.filter((i) => !forcedStaples.has(i.ingredient_name)),
      ...baseSendable.filter((i) => skippedPantry.has(normKey(i))),
    ];
    if (skippedFromCart.length > 0) {
      setConfirmSend({ sendable: finalSendable, skipped: skippedFromCart });
      return;
    }

    await submitToInstacart(finalSendable);
  }

