function KrogerSheet({
  visible, status, products, total, connected, itemsAdded, error,
  onConnect, onAddToCart, onClose,
}: {
  visible: boolean;
  status: KrogerStatus;
  products: KrogerProduct[];
  total: number | null;
  connected: boolean;
  itemsAdded: number;
  error: string | null;
  onConnect: () => void;
  onAddToCart: () => void;
  onClose: () => void;
}) {
  const colors = useTheme();
  const isLoading = status === 'searching' || status === 'adding' || status === 'oauth';

  return (
    <Modal visible={visible} animationType="slide" transparent presentationStyle="overFullScreen">
      <View style={{ flex: 1, backgroundColor: 'rgba(0,0,0,0.45)', justifyContent: 'flex-end' }}>
        <Pressable style={{ ...StyleSheet.absoluteFillObject }} onPress={isLoading ? undefined : onClose} />
        <View style={{
          backgroundColor: colors.card,
          borderTopLeftRadius: 20, borderTopRightRadius: 20,
          paddingBottom: 36, maxHeight: '85%',
        }}>
          {/* Handle */}
          <View style={{
            width: 36, height: 4, borderRadius: 2, backgroundColor: colors.border,
            alignSelf: 'center', marginTop: 12, marginBottom: 4,
          }} />

          {/* Header */}
          <View style={{
            flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between',
            paddingHorizontal: 20, paddingVertical: 14,
          }}>
            <Text style={{ fontSize: 18, fontWeight: '700', color: colors.text }}>Order on Kroger</Text>
            {!isLoading && (
              <Pressable onPress={onClose} hitSlop={12}>
                <Ionicons name="close" size={22} color={colors.textMuted} />
              </Pressable>
            )}
          </View>

          {/* Loading */}
          {isLoading && (
            <View style={{ paddingVertical: 48, alignItems: 'center', gap: 16 }}>
              <ActivityIndicator size="large" color={colors.primary} />
              <Text style={{ color: colors.textMuted, fontSize: 15 }}>
                {status === 'searching' ? 'Searching Kroger...'
                  : status === 'oauth'    ? 'Waiting for Kroger login...'
                  : 'Adding to your cart...'}
              </Text>
            </View>
          )}

          {/* Error */}
          {status === 'error' && (
            <View style={{ paddingVertical: 32, paddingHorizontal: 20, alignItems: 'center', gap: 12 }}>
              <Ionicons name="alert-circle-outline" size={40} color={colors.error} />
              <Text style={{ color: colors.text, fontSize: 15, textAlign: 'center' }}>{error}</Text>
              <Pressable onPress={onClose} style={{
                borderRadius: 10, borderWidth: 1, borderColor: colors.border,
                paddingVertical: 10, paddingHorizontal: 24,
              }}>
                <Text style={{ color: colors.textMuted, fontSize: 14 }}>Dismiss</Text>
              </Pressable>
            </View>
          )}

          {/* Success */}
          {status === 'success' && (
            <View style={{ paddingVertical: 32, paddingHorizontal: 20, alignItems: 'center', gap: 14 }}>
              <View style={{
                width: 64, height: 64, borderRadius: 32,
                backgroundColor: colors.primaryLight,
                alignItems: 'center', justifyContent: 'center',
              }}>
                <Ionicons name="checkmark-circle" size={40} color={colors.primary} />
              </View>
              <Text style={{ fontSize: 20, fontWeight: '700', color: colors.text }}>
                {itemsAdded} item{itemsAdded !== 1 ? 's' : ''} added!
              </Text>
              {total != null && (
                <Text style={{ fontSize: 15, color: colors.textMuted }}>
                  Estimated total: ${total.toFixed(2)}
                </Text>
              )}
              <Pressable
                onPress={() => Linking.openURL('https://www.kroger.com/cart')}
                style={{
                  backgroundColor: colors.primary, borderRadius: 12,
                  paddingVertical: 14, paddingHorizontal: 32,
                  flexDirection: 'row', alignItems: 'center', gap: 8,
                }}
              >
                <Ionicons name="open-outline" size={18} color="white" />
                <Text style={{ color: 'white', fontSize: 16, fontWeight: '600' }}>Open Kroger Cart</Text>
              </Pressable>
            </View>
          )}

          {/* Results */}
          {status === 'results' && (
            <>
              <ScrollView
                contentContainerStyle={{ paddingHorizontal: 16, gap: 8, paddingBottom: 8 }}
                showsVerticalScrollIndicator={false}
              >
                {products.map((p, i) => (
                  <View key={i} style={{
                    flexDirection: 'row', alignItems: 'center',
                    backgroundColor: colors.background, borderRadius: 10,
                    paddingHorizontal: 14, paddingVertical: 12,
                    opacity: p.found ? 1 : 0.5,
                  }}>
                    <View style={{ flex: 1, marginRight: 12 }}>
                      <Text style={{ fontSize: 12, color: colors.textMuted, marginBottom: 2 }} numberOfLines={1}>
                        {p.query}
                      </Text>
                      {p.found ? (
                        <>
                          <Text style={{ fontSize: 15, fontWeight: '500', color: colors.text }} numberOfLines={2}>
                            {p.name}
                          </Text>
                          {p.size ? (
                            <Text style={{ fontSize: 12, color: colors.textMuted, marginTop: 2 }}>{p.size}</Text>
                          ) : null}
                        </>
                      ) : (
                        <Text style={{ fontSize: 13, color: colors.textMuted, fontStyle: 'italic' }}>
                          Not found on Kroger
                        </Text>
                      )}
                    </View>
                    {p.found && (
                      <Text style={{ fontSize: 16, fontWeight: '700', color: colors.primary }}>
                        {p.price != null ? `$${p.price.toFixed(2)}` : '—'}
                      </Text>
                    )}
                  </View>
                ))}
              </ScrollView>

              <View style={{
                paddingHorizontal: 16, paddingTop: 14, gap: 10,
                borderTopWidth: 1, borderTopColor: colors.border, marginTop: 8,
              }}>
                {total != null && (
                  <View style={{ flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center' }}>
                    <Text style={{ fontSize: 15, color: colors.textMuted }}>Estimated total</Text>
                    <Text style={{ fontSize: 18, fontWeight: '700', color: colors.text }}>${total.toFixed(2)}</Text>
                  </View>
                )}

                {connected ? (
                  <Pressable
                    onPress={onAddToCart}
                    style={{
                      backgroundColor: colors.primary, borderRadius: 12,
                      paddingVertical: 15, alignItems: 'center',
                      flexDirection: 'row', justifyContent: 'center', gap: 8,
                    }}
                  >
                    <Ionicons name="cart" size={18} color="white" />
                    <Text style={{ color: 'white', fontSize: 16, fontWeight: '600' }}>
                      Add {products.filter((p) => p.found).length} Items to Kroger Cart
                    </Text>
                  </Pressable>
                ) : (
                  <Pressable
                    onPress={onConnect}
                    style={{
                      backgroundColor: colors.primary, borderRadius: 12,
                      paddingVertical: 15, alignItems: 'center',
                      flexDirection: 'row', justifyContent: 'center', gap: 8,
                    }}
                  >
                    <Ionicons name="log-in-outline" size={18} color="white" />
                    <Text style={{ color: 'white', fontSize: 16, fontWeight: '600' }}>Connect Kroger Account</Text>
                  </Pressable>
                )}

                {!connected && (
                  <Text style={{ fontSize: 11, color: colors.textMuted, textAlign: 'center' }}>
                    Sign in once — items go straight to your Kroger cart
                  </Text>
                )}
              </View>
            </>
          )}
        </View>
      </View>
    </Modal>
  );
}

function GroceryRow({
  item,
  recipeMap,
  editMode,
  onToggle,
  onDelete,
}: {
  item: GroceryItem;
  recipeMap: Record<string, string>;
  editMode: boolean;
  onToggle: () => void;
  onDelete: () => void;
}) {
  const colors = useTheme();
  // Build a readable source label for this ingredient
  const sourceLabel = (() => {
    if (item.recipe_ids.length === 0) return null;
    if (item.recipe_ids.length === 1) {
      const name = recipeMap[item.recipe_ids[0]];
      return name ?? null;
    }
    return `${item.recipe_ids.length} recipes`;
  })();

  return (
    <Pressable
      onPress={editMode ? undefined : onToggle}
      style={{
        flexDirection: 'row', alignItems: 'center',
        backgroundColor: colors.card, borderRadius: 10,
        paddingVertical: 11, paddingHorizontal: 13,
        marginBottom: 6,
        borderWidth: 1,
        borderColor: item.checked ? colors.primaryLight : colors.border,
        gap: 12,
      }}
    >
      {/* Delete button in edit mode, checkbox otherwise */}
      {editMode ? (
        <Pressable onPress={onDelete} hitSlop={8}>
          <View style={{
            width: 22, height: 22, borderRadius: 11,
            backgroundColor: colors.error,
            alignItems: 'center', justifyContent: 'center',
          }}>
            <Ionicons name="remove" size={14} color="white" />
          </View>
        </Pressable>
      ) : (
        <View style={{
          width: 22, height: 22, borderRadius: 11,
          borderWidth: 1.5,
          borderColor: item.checked ? colors.primary : colors.border,
          backgroundColor: item.checked ? colors.primary : 'transparent',
          alignItems: 'center', justifyContent: 'center',
        }}>
          {item.checked && <Ionicons name="checkmark" size={13} color="white" />}
        </View>
      )}

      {/* Name + source label */}
      <View style={{ flex: 1 }}>
        <Text style={{
          fontSize: 15,
          color: item.checked ? colors.textMuted : colors.text,
          textDecorationLine: item.checked ? 'line-through' : 'none',
        }}>
          {item.ingredient_name}
        </Text>
        {sourceLabel && !item.checked && (
          <Text style={{ fontSize: 11, color: colors.textMuted, marginTop: 1 }} numberOfLines={1}>
            {sourceLabel}
          </Text>
        )}
      </View>

      {/* Quantity */}
      {(item.quantity || item.unit) ? (
        <Text style={{ fontSize: 13, color: colors.textMuted }}>
          {item.quantity}{item.unit ? ' ' + item.unit : ''}
        </Text>
      ) : null}
    </Pressable>
  );
}

function TallyItem({ icon, value, label }: { icon: string; value: number; label: string }) {
  const colors = useTheme();
  return (
    <View style={{ flex: 1, alignItems: 'center', gap: 2 }}>
      <Ionicons name={icon as any} size={18} color={colors.primary} />
      <Text style={{ fontSize: 18, fontWeight: '700', color: colors.primary }}>{value}</Text>
      <Text style={{ fontSize: 11, color: colors.primary, opacity: 0.75 }}>{label}</Text>
    </View>
  );
}

function TallyDivider() {
  const colors = useTheme();
  return (
    <View style={{ width: 1, backgroundColor: colors.primary, opacity: 0.2, marginHorizontal: 4, borderRadius: 1 }} />
  );
}
