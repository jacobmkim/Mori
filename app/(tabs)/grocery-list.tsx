// ── Category helpers ────────────────────────────────────────────────────────

const CATEGORIES = ['Produce', 'Meat & Seafood', 'Dairy', 'Pantry', 'Frozen', 'Other'];

function formatSkipLine(staples: number): string {
  return `Skipping ${staples} staple${staples === 1 ? '' : 's'} you likely have`;
}

// Pantry hints use a normalized (trimmed + lowercased) key so they line up with
// pantryHints from partitionForInstacart. forcedStaples below uses the raw
// ingredient_name to match the staples-modal Add toggle — keep these conventions
// separate or the toggles silently no-op.
const normKey = (i: { ingredient_name: string }) => i.ingredient_name.trim().toLowerCase();

function categorize(name: string): string {
  const n = name.toLowerCase();
  if (/tomato|cucumber|onion|garlic|ginger|lemon|lime|lettuce|spinach|kale|pepper|capsicum|carrot|zucchini|mushroom|broccoli|cauliflower|celery|herb|basil|parsley|coriander|cilantro|thyme|rosemary|mint|avocado|sweet potato|potato|corn|pea|bean sprout|bok choy/.test(n)) return 'Produce';
  if (/chicken|beef|pork|lamb|turkey|duck|salmon|tuna|shrimp|prawn|fish|cod|tilapia|crab|lobster|bacon|pancetta|sausage|mince|steak|fillet/.test(n)) return 'Meat & Seafood';
  if (/milk|cheese|cream|butter|yogurt|feta|parmesan|mozzarella|cheddar|brie|gouda|egg|creme fraiche|mascarpone/.test(n)) return 'Dairy';
  if (/pasta|spaghetti|rice|flour|oil|olive oil|salt|pepper|spice|cumin|masala|paprika|turmeric|oregano|cinnamon|sauce|bread|tortilla|soy sauce|fish sauce|vinegar|sugar|honey|stock|broth|lentil|chickpea|coconut milk|tomato paste|canned|tinned/.test(n)) return 'Pantry';
  if (/frozen|ice cream/.test(n)) return 'Frozen';
  return 'Other';
}

function buildClipboardText(items: GroceryItem[], recipes: Recipe[], date: string): string {
  const grouped: Record<string, GroceryItem[]> = {};
  for (const item of items) {
    if (item.checked) continue;
    const cat = categorize(item.ingredient_name);
    if (!grouped[cat]) grouped[cat] = [];
    grouped[cat].push(item);
  }

  const lines: string[] = [
    `Mori Grocery List — ${date}`,
    recipes.length > 0 ? `Meals: ${recipes.map((r) => r.title).join(', ')}` : '',
    '',
  ].filter((l, i) => i !== 1 || l !== '');

  for (const cat of CATEGORIES) {
    if (!grouped[cat]?.length) continue;
    lines.push(cat.toUpperCase());
    for (const item of grouped[cat]) {
      const qty = item.quantity ? ` — ${item.quantity}${item.unit ? ' ' + item.unit : ''}` : '';
      lines.push(`• ${item.ingredient_name}${qty}`);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('Generated by Mori');
  return lines.join('\n');
}

// ── Undo banner ──────────────────────────────────────────────────────────────

const UNDO_DURATION = 5000; // ms

function UndoBanner({ count, message, onUndo, onDismiss }: {
  count: number;
  message?: string;
  onUndo: () => void;
  onDismiss: () => void;
}) {
  const colors = useTheme();
  const opacity = useRef(new Animated.Value(0)).current;

  useEffect(() => {
    Animated.spring(opacity, { toValue: 1, useNativeDriver: true, speed: 20 }).start();
    const t = setTimeout(() => {
      Animated.timing(opacity, { toValue: 0, duration: 300, useNativeDriver: true }).start(onDismiss);
    }, UNDO_DURATION);
    return () => clearTimeout(t);
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  return (
    <Animated.View style={{
      position: 'absolute', bottom: 160, left: 16, right: 16,
      backgroundColor: '#1A1A1A', borderRadius: 12,
      paddingVertical: 14, paddingHorizontal: 16,
      flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between',
      opacity,
      shadowColor: '#000', shadowOffset: { width: 0, height: 4 },
      shadowOpacity: 0.2, shadowRadius: 8, elevation: 8,
    }}>
      <Text style={{ color: 'white', fontSize: 14 }}>
        {message ?? `${count} item${count !== 1 ? 's' : ''} removed`}
      </Text>
      <Pressable onPress={onUndo}>
        <Text style={{ color: colors.primaryLight, fontSize: 14, fontWeight: '700' }}>Undo</Text>
      </Pressable>
    </Animated.View>
  );
}

